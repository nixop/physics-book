export type TranslationKey = keyof typeof ru;

export function translate(locale: Locale, key: TranslationKey, variables: Record<string, string | number> = {}) {
  const template = (locale === 'en' ? en : ru)[key] ?? ru[key];
  return Object.entries(variables).reduce((text, [name, value]) => text.replaceAll(`{${name}}`, String(value)), template);
}
